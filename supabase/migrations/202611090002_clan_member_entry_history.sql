create table if not exists public.clan_member_entry_history (
  id bigint generated by default as identity primary key,
  player_tag text not null,
  player_name text not null,
  entered_at timestamptz not null default now(),
  is_baseline boolean not null default false,
  source text not null default 'clan_api'
);

create index if not exists clan_member_entry_history_entered_at_idx
  on public.clan_member_entry_history (entered_at desc);
create index if not exists clan_member_entry_history_player_tag_idx
  on public.clan_member_entry_history (player_tag, entered_at desc);

alter table public.clan_member_entry_history enable row level security;

insert into public.clan_member_entry_history
  (player_tag, player_name, entered_at, is_baseline, source)
select player_tag, player_name, first_seen_at, true, 'initial_baseline'
from public.clan_member_entries
where player_tag is not null
on conflict do nothing;
