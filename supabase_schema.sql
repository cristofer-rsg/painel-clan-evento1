create table if not exists public.players (
  name text primary key,
  eligible text not null default 'Elegível' check (eligible in ('Elegível','Inelegível')),
  whatsapp text not null default 'Sim' check (whatsapp in ('Sim','Não')),
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  player text not null references public.players(name) on update cascade on delete restrict,
  category text not null check (category in ('Guerras','Liga dos Clãs','Doações','Jogos do Clã')),
  activity text not null,
  points integer not null,
  created_at timestamptz not null default now()
);

create index if not exists events_player_idx on public.events(player);
create index if not exists events_created_at_idx on public.events(created_at desc);

-- O aplicativo acessa o banco pelo servidor usando SUPABASE_SERVICE_ROLE_KEY.
-- Não coloque a service_role key no código nem em repositório GitHub.
-- RLS fica habilitado; a chave service_role usada apenas no backend ignora RLS.
alter table public.players enable row level security;
alter table public.events enable row level security;
