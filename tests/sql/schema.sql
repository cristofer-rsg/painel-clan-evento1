-- Minimal disposable schema for SQL function tests. No production data.
CREATE TABLE public.players (
  name text PRIMARY KEY,
  eligible text NOT NULL DEFAULT 'Elegível',
  whatsapp text NOT NULL DEFAULT 'Sim',
  created_at timestamptz NOT NULL DEFAULT now(),
  player_tag text,
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE public.events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player text NOT NULL REFERENCES public.players(name),
  category text NOT NULL,
  activity text NOT NULL,
  points integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  player_tag text
);
CREATE TABLE public.clash_league_automation (
  source_key text PRIMARY KEY, war_key text NOT NULL, player_tag text NOT NULL,
  event_id text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.player_monthly_stat_sources (
  month_key text NOT NULL CHECK (month_key ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  source_key text NOT NULL, player_tag text NOT NULL, player text NOT NULL,
  war_attacks integer NOT NULL DEFAULT 0, league_attacks integer NOT NULL DEFAULT 0,
  raid_attacks integer NOT NULL DEFAULT 0, updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(month_key,source_key),
  CHECK (war_attacks >= 0 AND league_attacks >= 0 AND raid_attacks >= 0)
);
CREATE TABLE public.player_monthly_stats (
  month_key text NOT NULL CHECK (month_key ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  player_tag text NOT NULL, player text NOT NULL,
  war_attacks integer NOT NULL DEFAULT 0, league_attacks integer NOT NULL DEFAULT 0,
  raid_attacks integer NOT NULL DEFAULT 0, donations integer NOT NULL DEFAULT 0,
  clan_games_points integer NOT NULL DEFAULT 0, updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(month_key,player_tag),
  CHECK (war_attacks >= 0 AND league_attacks >= 0 AND raid_attacks >= 0 AND donations >= 0 AND clan_games_points >= 0)
);
CREATE TABLE public.clash_donation_totals (
  month_key text NOT NULL, player_tag text NOT NULL, player text NOT NULL,
  total_donated bigint NOT NULL DEFAULT 0, last_api_donations bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(month_key,player_tag)
);
CREATE TABLE public.clash_donation_events (
  month_key text NOT NULL, player_tag text NOT NULL, event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  points integer NOT NULL, PRIMARY KEY(month_key,player_tag)
);
CREATE TABLE public.clash_games_tracking (
  month_key text NOT NULL, player_tag text NOT NULL, player text NOT NULL,
  baseline_value bigint NOT NULL, latest_value bigint NOT NULL, points_earned bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(month_key,player_tag)
);
CREATE TABLE public.clash_games_events (
  month_key text NOT NULL, player_tag text NOT NULL, event_id bigint NOT NULL REFERENCES public.events(id) ON DELETE CASCADE,
  points integer NOT NULL, PRIMARY KEY(month_key,player_tag)
);
CREATE TABLE public.clash_games_auto_state (
  singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
  active_month text, event_started_at timestamptz, updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.clash_games_observer (
  player_tag text PRIMARY KEY, player text NOT NULL, last_value bigint NOT NULL CHECK(last_value >= 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.capital_gold_sync_state (
  player_tag text PRIMARY KEY, player text NOT NULL, last_total bigint NOT NULL DEFAULT 0,
  started_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  baseline_total bigint, baseline_at timestamptz
);
CREATE TABLE public.capital_gold_sync_snapshots (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, player_tag text NOT NULL, player text NOT NULL,
  api_total bigint NOT NULL CHECK(api_total >= 0), observed_at timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION public.test_fill_event_player_tag()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.player_tag IS NULL OR btrim(NEW.player_tag) = '' THEN
    SELECT min(player_tag) INTO NEW.player_tag
    FROM public.players
    WHERE player_tag IS NOT NULL AND lower(btrim(name))=lower(btrim(NEW.player))
    GROUP BY lower(btrim(name)) HAVING count(*)=1;
  END IF;
  RETURN NEW;
END $$;

